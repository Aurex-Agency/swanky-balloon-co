// Splits Jenn's master logo (public/swanky/brand/logo/swanky-logo.svg, from the client's
// LOGO FILES Drive folder) into typed path data the site renders inline.
// Shapes 0–5 are the SB monogram with balloon; 6–21 the SWANKY / BALLOON CO. wordmark.
// Usage: npm run brand:logo
import { readFileSync, writeFileSync } from "node:fs";

const raw = readFileSync("public/swanky/brand/logo/swanky-logo.svg", "utf8");
const shapes = raw
  .match(/<(path|polygon)\b[^>]*\/>/g)
  .map((s) => s.replace(/\s+class="st\d"/, "").replace(/\s+/g, " "));
if (shapes.length !== 22)
  throw new Error(`Expected 22 logo shapes, found ${shapes.length}`);

writeFileSync(
  "src/lib/swanky/logo-shapes.ts",
  `// Generated by scripts/extract-logo.mjs from public/swanky/brand/logo/swanky-logo.svg. Do not edit.
export const MONOGRAM_SHAPES = ${JSON.stringify(shapes.slice(0, 6).join(""))};
export const WORDMARK_SHAPES = ${JSON.stringify(shapes.slice(6).join(""))};
// Bounding boxes in the master file's 2000×2000 coordinate space, measured in the browser.
export const MONOGRAM_BOX = { x: 649, y: 335, w: 853, h: 989 };
export const FULL_BOX = { x: 342, y: 335, w: 1320, h: 1349 };
`,
);
console.log("Wrote src/lib/swanky/logo-shapes.ts");
